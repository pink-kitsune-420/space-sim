import type { ServiceKey } from './modules-v2';
import type { Disposable } from './modules';
import type { TextConnection } from './platform';

/**
 * Diagnostic metrics for a WebRTC peer connection.
 * Exposes counts and state codes only; never IP addresses, raw SDP or secrets.
 */
export interface ConnectionDiagnostics {
  /** Current ICE gathering state (e.g. 'new', 'gathering', 'complete'). */
  readonly gathering: RTCIceGatheringState;
  /** Current peer connection state (e.g. 'new', 'connecting', 'connected', 'disconnected', 'failed', 'closed'). */
  readonly connection: RTCPeerConnectionState;
  /** Count of gathered ICE candidates grouped by candidate type (host, srflx, relay). */
  readonly candidates: Readonly<Record<string, number>>;
  /** Numerical error codes encountered during ICE or handshake. */
  readonly errors: readonly number[];
}
/** Active manual WebRTC invitation created by a session host. */
export interface ManualInvite extends Disposable {
  /** Compact base64url encoded invitation code containing compressed SDP offer. */
  readonly code: string;
  /** Whether STUN reflex candidate gathering was enabled for this invitation. */
  readonly stun: boolean;
  /** Return current connection and ICE gathering diagnostics. */
  diagnostics(): ConnectionDiagnostics;
  /** Accept a guest's reply code to finalize the connection. Resolves to the established TextConnection. */
  accept(reply: string): Promise<TextConnection>;
}
/** Active manual WebRTC reply generated by a joining guest in response to an invitation. */
export interface ManualReply extends Disposable {
  /** Compact base64url encoded reply code containing compressed SDP answer. */
  readonly code: string;
  /** Expiration timestamp in milliseconds (epoch) after which the reply is invalid. */
  readonly expiresAt: number;
  /** Return current connection and ICE gathering diagnostics. */
  diagnostics(): ConnectionDiagnostics;
  /** Resolves to the established TextConnection once the host accepts the reply. */
  readonly connection: Promise<TextConnection>;
}
/**
 * Manual WebRTC signaling provider exchanging copy-paste invite/reply codes for peer-to-peer data channels.
 */
export interface ManualSignalingProvider {
  /** Create a new invitation offer. Signal owns the invite lifecycle and pending gathering. */
  create(stun: boolean, signal: AbortSignal): Promise<ManualInvite>;
  /** Answer an invitation offer code, generating a reply code and pending connection promise. */
  answer(offer: string, signal: AbortSignal): Promise<ManualReply>;
  /** Validate whether text matches the expected invitation code format. */
  isInviteCode(text: string): boolean;
  /** Validate whether text matches the expected reply code format. */
  isReplyCode(text: string): boolean;
}
/** ServiceKey for manual WebRTC invite/reply signaling (slot `net.webrtc-signaling`). */
export const WEBRTC_SIGNALING: ServiceKey<ManualSignalingProvider> = Object.freeze({ slot: 'net.webrtc-signaling', version: '1.0.0' });
